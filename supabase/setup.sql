-- Podify database setup. Run once in the Supabase SQL editor
-- (or let your agent run it with `psql "$DATABASE_URL" -f supabase/setup.sql`).

create table if not exists public.episodes (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references auth.users (id) on delete cascade,
  url         text not null,
  title       text not null,
  script      text not null,
  audio_url   text not null,
  created_at  timestamptz not null default now()
);

create index if not exists episodes_user_created_idx
  on public.episodes (user_id, created_at desc);

alter table public.episodes enable row level security;

-- Signed-in users can read their own episodes. Writes happen server-side
-- with the service key, and public share pages are rendered server-side too.
drop policy if exists "read own episodes" on public.episodes;
create policy "read own episodes" on public.episodes
  for select to authenticated
  using (auth.uid() = user_id);

-- Public bucket for the MP3s (the API also creates it on first use).
insert into storage.buckets (id, name, public)
values ('episodes', 'episodes', true)
on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- Personalised episodes + private podcast feed. Safe to run more than once.

alter table public.episodes add column if not exists takeaways   jsonb not null default '[]'::jsonb;
alter table public.episodes add column if not exists action      text;
alter table public.episodes add column if not exists audio_bytes integer;

-- One row per user: who they are (shapes every script) and the secret token
-- behind their private RSS feed at /feed/<feed_token>.
create table if not exists public.profiles (
  user_id     uuid primary key references auth.users (id) on delete cascade,
  role        text not null default '',
  goal        text not null default '',
  feed_token  uuid not null unique default gen_random_uuid(),
  updated_at  timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "create own profile" on public.profiles;
create policy "create own profile" on public.profiles
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "update own profile" on public.profiles;
create policy "update own profile" on public.profiles
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Users may set role and goal only; feed_token is generated by the database.
revoke insert, update on public.profiles from authenticated, anon;
grant select on public.profiles to authenticated;
grant insert (user_id, role, goal) on public.profiles to authenticated;
grant update (role, goal, updated_at) on public.profiles to authenticated;
